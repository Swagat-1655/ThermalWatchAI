let CURRENT_LANG = localStorage.getItem('tw_lang') || 'en';

const T = (key, fallback) => {
  const dict = I18N[CURRENT_LANG] || I18N.en;
  return dict[key] || I18N.en[key] || fallback || key;
};

function applyI18n() {
  document.documentElement.lang = CURRENT_LANG;
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const v = T(el.getAttribute('data-i18n'));
    if (v !== undefined) el.textContent = v;
  });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => {
    const v = T(el.getAttribute('data-i18n-ph'));
    if (v !== undefined) el.placeholder = v;
  });
  document.querySelectorAll('[data-i18n-title]').forEach(el => {
    const v = T(el.getAttribute('data-i18n-title'));
    if (v !== undefined) el.title = v;
  });
}

function setLang(lang) {
  CURRENT_LANG = lang;
  localStorage.setItem('tw_lang', lang);
  applyI18n();
  document.querySelectorAll('.lang-btn').forEach(b => b.classList.toggle('active', b.dataset.lang === lang));
  // Re-render dynamic content that carries translated labels
  if (window.App && typeof App.onLangChange === 'function') App.onLangChange();
}